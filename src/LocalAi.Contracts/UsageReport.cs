namespace LocalAi.Contracts;

public enum UsageValueStatus { Measured, Estimated, Unknown, NotApplicable }
public enum UsageTechnicalOutcome { Unknown, Succeeded, Failed, Refused, Cancelled }
public enum UsageValidation { Unknown, Passed, Failed, NotApplicable }
public enum UsageDelivery { Unknown, Delivered, Failed, NotAttempted, NotApplicable }
public enum UsageModelState { Unknown, NotCalled, Called, Loaded }
public enum UsageCache { Unknown, Hit, Miss, NotApplicable }
public enum UsageOffload { Unknown, None, Partial, Cpu }

// Durations are independent observations: execution across parallel attempts may exceed elapsed.
public enum UsageTiming { ElapsedMilliseconds, QueueMilliseconds, LoadMilliseconds, ExecutionMilliseconds, ValidationMilliseconds, WriteMilliseconds }
// Backend token counts are diagnostics, never a substitute for cloud tokenizer counts.
public enum UsageVolume { InputBytes, InputCharacters, Images, Pages, BackendPromptTokens, BackendEvalTokens, ResponseBytes, ResponseCharacters }
// InputSaved describes context reduction; OutputSaved describes replaced generation. There is
// deliberately no aggregate field that could add overlapping estimates a second time.
public enum UsageCloudTokens { InputWithoutDelegation, InputWithDelegation, InputSaved, OutputWithoutDelegation, OutputWithDelegation, OutputSaved }

public sealed record UsageRange(long Lower, long Upper, string Basis);

/// <summary>
/// A known zero differs from unavailable data. Estimated values require a named method and
/// either a supported range or its non-applicability reason; neither is generated by a model.
/// Reason/method/profile fields are stable identifiers, not prompts or model-produced prose.
/// </summary>
public sealed record UsageValue(UsageValueStatus Status, long? Value, string? Reason = null,
    string? Method = null, UsageRange? Range = null, string? RangeReason = null)
{
    public static UsageValue Measured(long value) => new(UsageValueStatus.Measured, value);
    public static UsageValue Estimated(long value, string method, UsageRange? range = null, string? rangeReason = "not_calibrated") =>
        new(UsageValueStatus.Estimated, value, Method: method, Range: range, RangeReason: range is null ? rangeReason : null);
    public static UsageValue Unknown(string reason = "not_recorded") => new(UsageValueStatus.Unknown, null, reason);
    public static UsageValue NotApplicable(string reason) => new(UsageValueStatus.NotApplicable, null, reason);
}

public sealed record UsageIdentity(UsageSurface Surface, string Component, string Operation, Guid CallId,
    Guid? WorkflowId, IReadOnlyList<Guid> JobIds, IReadOnlyList<Guid> AttemptIds);

public sealed record UsageOutcome(UsageTechnicalOutcome Technical, UsageValidation Validation, UsageDelivery Delivery,
    string? TechnicalReason, string? ValidationReason, string? DeliveryReason);

public sealed record UsageModelUse(string Model, long Calls, UsageOffload Offload, string? OffloadReason);

public sealed record UsageModels(UsageModelState State, UsageValue Calls, IReadOnlyList<UsageModelUse> Actual,
    UsageCache Cache, string? CacheReason)
{
    public static UsageModels Unrecorded() => new(UsageModelState.Unknown, UsageValue.Unknown(), [], UsageCache.Unknown, "not_recorded");
    public static UsageModels NoCall() => new(UsageModelState.NotCalled, UsageValue.Measured(0), [], UsageCache.Unknown, "not_recorded");
}

public sealed record UsageComparison(string? ScenarioId, string? TokenizerProfile, string? VisionProfile);

/// <summary>Full hypothetical cloud input minus the text returned to the cloud agent.</summary>
public sealed record CloudContextEstimate(string Methodology, string TokenizerProfile, string? VisionProfile,
    UsageValue InputTokens, UsageValue ReturnedTokens, UsageValue SavedTokens);

/// <summary>
/// One application-owned record per surface call. Attempts/jobs are links, not additional
/// delivered answers. This schema is independent of MachineEnvelope and LocalUsageReceipt;
/// existing consumers keep their wire formats. Serialize through UsageReportJson to validate.
/// </summary>
public sealed record UsageReport(int SchemaVersion, string MethodologyVersion, UsageIdentity Identity,
    UsageOutcome Outcome, UsageModels Models, IReadOnlyDictionary<UsageTiming, UsageValue> Timings,
    IReadOnlyDictionary<UsageVolume, UsageValue> Volumes, UsageComparisonKind ComparisonKind,
    UsageComparison Comparison, IReadOnlyDictionary<UsageCloudTokens, UsageValue> CloudTokens)
{
    // Optional so old persisted reports retain their original comparison semantics.
    [System.Text.Json.Serialization.JsonIgnore(Condition = System.Text.Json.Serialization.JsonIgnoreCondition.WhenWritingNull)]
    public CloudContextEstimate? ContextEstimate { get; init; }

    public const int CurrentSchemaVersion = 1;
    public const int ContextEstimateSchemaVersion = 2;
    // Versions the status, unit and difference rules, not a calibrated estimation algorithm.
    public const string CurrentMethodologyVersion = "usage-contract-v1";

    internal static UsageReport Create(UsageOperation operation, Guid callId)
    {
        if (callId == Guid.Empty) throw new ArgumentException("A call ID is required.", nameof(callId));
        return new(CurrentSchemaVersion, CurrentMethodologyVersion,
            new(operation.Surface, operation.Component, operation.Operation, callId, null, [], []),
            new(UsageTechnicalOutcome.Unknown, UsageValidation.Unknown, UsageDelivery.Unknown, "not_recorded", "not_recorded", "not_recorded"),
            UsageModels.Unrecorded(), Values<UsageTiming>(UsageValue.Unknown()), Values<UsageVolume>(UsageValue.Unknown()),
            operation.Policy.Comparison, new(null, null, null), Values<UsageCloudTokens>(
                operation.Policy.Comparison == UsageComparisonKind.NotApplicable
                    ? UsageValue.NotApplicable("administrative_operation") : UsageValue.Unknown("comparison_not_recorded")));
    }

    private static IReadOnlyDictionary<T, UsageValue> Values<T>(UsageValue value) where T : struct, Enum =>
        new System.Collections.ObjectModel.ReadOnlyDictionary<T, UsageValue>(Enum.GetValues<T>().ToDictionary(key => key, _ => value));
}
